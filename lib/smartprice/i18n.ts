export function tr(key: string, lang: Lang) {
  const r = rows[key] || errors[key];
  return r ? r[lang === 'ru' ? 0 : lang === 'kk' ? 1 : 2] : key;
}

export function errorText(code: string, lang: Lang) {
  const [key, line] = String(code || '').split('|');
  return (errors[key] ? tr(key, lang) : tr('server_error', lang)) + (line ? ` · ${lang === 'ru' ? 'строка' : lang === 'kk' ? 'жол' : 'row'} ${line}` : '');
}

export function productName(p: any, lang: Lang) {
  if (!p) return '';
  return lang === 'en' ? p.name_en : lang === 'kk' ? p.name_kk : p.name;
}

